const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const source = fs.readFileSync(path.join(__dirname, "../behavior_pack/Nonax_Architect_Pack/scripts/workbench-ledger.js"), "utf8")
  .replace(/^export /gm, "");
const context = vm.createContext({});
vm.runInContext(`${source}\nthis.api = { createWorkbenchRecord, validateWorkbenchRecord, bindArchitect, bindCarpenter, carpenterDied, recordBuildCount, beginRecovery, finishRecovery, placeRecoveredWorkbench, forgetRetiredArchitect };`, context);
const api = context.api;
const pos = { dimension: "minecraft:overworld", x: 1, y: 64, z: 2 };
const other = { dimension: "minecraft:overworld", x: 20, y: 64, z: 2 };

let record = api.createWorkbenchRecord("workbench-1", pos);
assert.equal(record.state, "placed");
assert.throws(() => api.createWorkbenchRecord("", pos));
assert.throws(() => api.createWorkbenchRecord("bad", { ...pos, x: 0.5 }));
record = api.bindArchitect(record, "old");
assert.throws(() => api.bindArchitect(record, "other"));
assert.throws(() => api.recordBuildCount(record, "other", 1));
assert.throws(() => api.recordBuildCount(record, "old", 2));
record = api.recordBuildCount(record, "old", 1);
const recovering = api.beginRecovery(record);
assert.equal(recovering.state, "recovering");
assert.equal(recovering.architectId, undefined);
assert(recovering.retiredArchitectIds.includes("old"));
assert.throws(() => api.beginRecovery(recovering));
assert.throws(() => api.placeRecoveredWorkbench(recovering, other));
assert.equal(record.architectId, "old");
record = api.finishRecovery(recovering, false);
assert.equal(record.state, "carried");
assert.throws(() => api.finishRecovery(record, false));
record = api.placeRecoveredWorkbench(record, other);
assert.equal(record.buildCount, 1);
assert.equal(record.position.x, 20);
assert.throws(() => api.placeRecoveredWorkbench(record, other));
assert.throws(() => api.bindArchitect(record, "old"));
record = api.bindArchitect(record, "new");
assert(record.retiredArchitectIds.includes("old"));
record = api.forgetRetiredArchitect(record, "old");
assert.equal(record.retiredArchitectIds.length, 0);
assert.throws(() => api.forgetRetiredArchitect(record, "old"));
const revoked = api.finishRecovery(api.beginRecovery(record), true);
assert.equal(revoked.state, "revoked");
assert.throws(() => api.placeRecoveredWorkbench(revoked, pos));
assert.throws(() => api.bindArchitect({ ...record, buildCount: -1 }, "another"));
let crew = api.bindArchitect(api.createWorkbenchRecord("crew", pos), "leader");
crew = api.bindCarpenter(crew, "worker-1", 1);
assert.throws(() => api.bindCarpenter(crew, "worker-2", 1));
assert.throws(() => api.bindCarpenter(crew, "worker-1", 2));
assert.throws(() => api.carpenterDied(crew, "other"));
crew = api.carpenterDied(crew, "worker-1");
crew = api.bindCarpenter(crew, "worker-2", 1);
crew = api.beginRecovery(crew);
assert.equal(crew.carpenterIds.length, 0);
assert(crew.retiredCarpenterIds.includes("worker-2"));
crew = api.placeRecoveredWorkbench(api.finishRecovery(crew, false), other);
crew = api.bindArchitect(crew, "leader-2");
assert.throws(() => api.bindCarpenter(crew, "worker-2", 1));
assert.throws(() => api.validateWorkbenchRecord({ ...crew, carpenterIds: ["same", "same"] }));
console.log("Workbench ledger transition tests passed");
